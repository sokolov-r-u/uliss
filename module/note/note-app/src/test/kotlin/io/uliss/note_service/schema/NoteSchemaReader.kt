package io.uliss.note_service.schema

import org.springframework.jdbc.core.JdbcTemplate

/** Reads the migrated `note` schema from the Postgres catalog. */
class NoteSchemaReader(private val jdbcTemplate: JdbcTemplate) {

    fun tables(): Set<String> = jdbcTemplate.queryForList(
        """
        SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = '$SCHEMA' AND c.relkind IN ('r', 'p') AND c.relname <> 'flyway_schema_history'
        """.trimIndent(),
        String::class.java,
    ).filterNotNull().toSet()

    fun extensions(): List<SchemaExtension> = jdbcTemplate.query(
        """
        SELECT e.extname, n.nspname, e.extversion FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
        WHERE e.extname <> 'plpgsql' ORDER BY e.extname
        """.trimIndent(),
    ) { rs, _ -> SchemaExtension(rs.getString(1), rs.getString(2), rs.getString(3)) }

    /** Objects of the schema that the table view and the extension list do not show, as "kind name". */
    fun strayObjects(): List<String> = jdbcTemplate.queryForList(STRAY_OBJECTS_SQL, String::class.java).filterNotNull()

    fun table(table: String): TableSchema {
        val relation = "$SCHEMA.$table"
        val comment = jdbcTemplate.queryForObject(
            "SELECT obj_description(?::regclass, 'pg_class')", String::class.java, relation,
        )
        val columns = jdbcTemplate.query(COLUMNS_SQL, { rs, _ ->
            val default = when {
                rs.getString("attidentity") == "a" -> "generated always as identity"
                rs.getString("attidentity") == "d" -> "generated by default as identity"
                rs.getString("attgenerated") == "s" -> "generated always as (${rs.getString("expr")}) stored"
                rs.getString("attgenerated") == "v" -> "generated always as (${rs.getString("expr")}) virtual"
                else -> rs.getString("expr")
            }
            TableColumn(
                rs.getString("attname"), rs.getString("type"), !rs.getBoolean("attnotnull"), default,
                rs.getString("comment"),
            )
        }, relation)
        val constraints = jdbcTemplate.query(CONSTRAINTS_SQL, { rs, _ ->
            TableConstraint(
                rs.getString("conname"), rs.getString("contype").single(), rs.getString("definition"),
                rs.getString("columns").split(','), rs.getString("references"),
            )
        }, relation)
        val indexes = jdbcTemplate.query(INDEXES_SQL, { rs, _ ->
            val ddl = rs.getString("ddl")
            TableIndex(rs.getString("relname"), rs.getBoolean("indisunique"), ddl.substringAfter(" USING "))
        }, relation)
        return TableSchema(table, comment, columns, constraints, indexes)
    }

    private companion object {
        const val SCHEMA = "note"

        val COLUMNS_SQL = """
            SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull, a.attidentity,
                   a.attgenerated, pg_get_expr(d.adbin, d.adrelid) AS expr, col_description(a.attrelid, a.attnum) AS comment
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE a.attrelid = ?::regclass AND a.attnum > 0 AND NOT a.attisdropped
            ORDER BY a.attnum
        """.trimIndent()

        // NOT NULL constraints (contype 'n', PG 18) are already the Null column
        val CONSTRAINTS_SQL = """
            SELECT c.conname, c.contype, pg_get_constraintdef(c.oid, true) AS definition,
                   (SELECT string_agg(a.attname, ',' ORDER BY k.ord) FROM unnest(c.conkey) WITH ORDINALITY k(attnum, ord)
                    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum) AS columns,
                   (SELECT r.relname FROM pg_class r WHERE r.oid = c.confrelid) AS references
            FROM pg_constraint c
            WHERE c.conrelid = ?::regclass AND c.contype IN ('p', 'u', 'f', 'c', 'x')
            ORDER BY array_position(ARRAY['p', 'u', 'x', 'f', 'c'], c.contype::text), c.conname
        """.trimIndent()

        // indexes behind PRIMARY KEY / UNIQUE / EXCLUDE constraints are shown as those constraints
        val INDEXES_SQL = """
            SELECT i.relname, x.indisunique, pg_get_indexdef(x.indexrelid) AS ddl
            FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid
            WHERE x.indrelid = ?::regclass
              AND NOT EXISTS (SELECT 1 FROM pg_constraint c
                              WHERE c.conindid = x.indexrelid AND c.conrelid = x.indrelid AND c.contype IN ('p', 'u', 'x'))
            ORDER BY i.relname
        """.trimIndent()

        // Members of an extension (deptype 'e') and sequences owned by a column (identity 'i', serial 'a') are skipped;
        // array types follow their element type, and a table's row type follows the table.
        val STRAY_OBJECTS_SQL = """
            SELECT kind || ' ' || name FROM (
                SELECT CASE c.relkind WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized view'
                           WHEN 'S' THEN 'sequence' ELSE 'relation' END AS kind,
                       c.relname AS name, 'pg_class'::regclass AS classid, c.oid AS objid
                FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = '$SCHEMA' AND c.relkind IN ('v', 'm', 'S', 'f')
                  AND NOT EXISTS (SELECT 1 FROM pg_depend d
                                  WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid
                                    AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i'))
                UNION ALL
                SELECT CASE p.prokind WHEN 'p' THEN 'procedure' WHEN 'a' THEN 'aggregate' ELSE 'function' END,
                       p.proname, 'pg_proc'::regclass, p.oid
                FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname = '$SCHEMA'
                UNION ALL
                SELECT 'type', t.typname, 'pg_type'::regclass, t.oid
                FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
                WHERE n.nspname = '$SCHEMA' AND t.typcategory <> 'A'
                  AND (t.typrelid = 0 OR (SELECT c.relkind FROM pg_class c WHERE c.oid = t.typrelid) = 'c')
                UNION ALL
                SELECT 'trigger', t.tgname || ' on ' || c.relname, 'pg_trigger'::regclass, t.oid
                FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = '$SCHEMA' AND NOT t.tgisinternal
                UNION ALL
                SELECT 'policy', p.polname || ' on ' || c.relname, 'pg_policy'::regclass, p.oid
                FROM pg_policy p JOIN pg_class c ON c.oid = p.polrelid JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = '$SCHEMA'
            ) o
            WHERE NOT EXISTS (SELECT 1 FROM pg_depend d
                              WHERE d.classid = o.classid AND d.objid = o.objid AND d.deptype = 'e')
            ORDER BY 1
        """.trimIndent()
    }
}
