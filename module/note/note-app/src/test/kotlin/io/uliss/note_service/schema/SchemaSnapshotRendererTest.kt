package io.uliss.note_service.schema

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import kotlin.test.assertEquals

class SchemaSnapshotRendererTest {

    private val sections = listOf(
        SchemaSection("User profile", "Profile tables.", listOf("user_profile_input", "user_profile")),
        SchemaSection("RAG", "Chunks.", listOf("rag_chunks")),
    )
    private val ddl = mapOf(
        "user_profile" to "CREATE TABLE note.user_profile ();",
        "user_profile_input" to "CREATE TABLE note.user_profile_input ();",
        "rag_chunks" to "CREATE TABLE note.rag_chunks ();",
    )

    @Test
    fun `renders contents, extensions and sections with tables in map order`() {
        val text = SchemaSnapshotRenderer.render(listOf(SchemaExtension("vector", "note", "0.8.2")), sections, ddl)

        assertEquals(
            """
            |# Note service database schema
            |
            |The `note` schema after every Flyway migration, grouped by area. Generated by
            |`NoteSchemaSnapshotIntegrationTest` from `pg_dump`; do not edit by hand.
            |Update after a new migration: `./gradlew :note:updateSchemaSnapshot`.
            |
            |## Contents
            |
            |- [Extensions](#extensions)
            |- [User profile](#user-profile) — `user_profile_input`, `user_profile`
            |- [RAG](#rag) — `rag_chunks`
            |
            |## Extensions
            |
            |```sql
            |CREATE EXTENSION vector WITH SCHEMA note; -- version 0.8.2
            |```
            |
            |## User profile
            |
            |Profile tables.
            |
            |### `user_profile_input`
            |
            |```sql
            |CREATE TABLE note.user_profile_input ();
            |```
            |
            |### `user_profile`
            |
            |```sql
            |CREATE TABLE note.user_profile ();
            |```
            |
            |## RAG
            |
            |Chunks.
            |
            |### `rag_chunks`
            |
            |```sql
            |CREATE TABLE note.rag_chunks ();
            |```
            |
            """.trimMargin(),
            text,
        )
    }

    @Test
    fun `a mapped table without DDL is an error, not an empty block`() {
        val error = assertThrows<IllegalArgumentException> {
            SchemaSnapshotRenderer.render(emptyList(), sections, ddl - "rag_chunks")
        }

        assertEquals("No DDL for table rag_chunks", error.message)
    }
}
