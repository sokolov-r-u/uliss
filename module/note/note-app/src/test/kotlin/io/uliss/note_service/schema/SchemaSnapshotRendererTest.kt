package io.uliss.note_service.schema

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class SchemaSnapshotRendererTest {

    private val posters = TableSchema(
        name = "note_posters",
        comment = null,
        columns = listOf(
            TableColumn("note_id", "uuid", nullable = false, default = null, comment = null),
            TableColumn("url", "character varying(2048)", nullable = false, default = null, comment = null),
            TableColumn("crop", "jsonb", nullable = true, default = null, comment = null),
        ),
        constraints = listOf(
            TableConstraint("note_posters_pkey", 'p', "PRIMARY KEY (note_id)", listOf("note_id")),
            TableConstraint(
                "note_posters_note_id_fkey", 'f',
                "FOREIGN KEY (note_id) REFERENCES note.notes(id) ON DELETE CASCADE", listOf("note_id"), "notes", listOf("id"),
            ),
        ),
        indexes = emptyList(),
    )
    private val chunks = TableSchema(
        name = "rag_chunks",
        comment = "Embedded note chunks.",
        columns = listOf(
            TableColumn("id", "bigint", nullable = false, default = "generated always as identity", comment = "Row id"),
            TableColumn("content", "text", nullable = false, default = "''::text", comment = null),
        ),
        constraints = listOf(TableConstraint("rag_chunks_pkey", 'p', "PRIMARY KEY (id)", listOf("id"))),
        indexes = listOf(
            TableIndex("idx_rag_chunks_content", unique = false, definition = "btree (content)"),
            TableIndex("uq_rag_chunks_content", unique = true, definition = "btree (lower(content))"),
        ),
    )
    private val sections = listOf(
        SchemaSection("Notes", "Notes and posters.", listOf("note_posters")),
        SchemaSection("RAG", "Chunks.", listOf("rag_chunks")),
    )

    @Test
    fun `renders contents, extensions and a column table per table in map order`() {
        val text = SchemaSnapshotRenderer.render(
            listOf(SchemaExtension("vector", "note", "0.8.2")),
            sections,
            mapOf("note_posters" to posters, "rag_chunks" to chunks),
        )

        assertEquals(
            """
            |# Note service database schema
            |
            |The `note` schema after every Flyway migration, grouped by area. Generated by
            |`NoteSchemaSnapshotIntegrationTest` from the Postgres catalog; do not edit by hand.
            |Update after a new migration: `./gradlew :note:updateSchemaSnapshot`.
            |
            |## Contents
            |
            |- [Extensions](#extensions)
            |- [Notes](#notes) — `note_posters`
            |- [RAG](#rag) — `rag_chunks`
            |
            |## Extensions
            |
            |- `vector` 0.8.2 in schema `note`
            |
            |## Notes
            |
            |Notes and posters.
            |
            |### `note_posters`
            |
            || Column | Type | Null | Default | Key |
            ||---|---|---|---|---|
            || `note_id` | `uuid` | no |  | PK, FK → notes.id |
            || `url` | `character varying(2048)` | no |  |  |
            || `crop` | `jsonb` | yes |  |  |
            |
            |Constraints:
            |
            |- `note_posters_pkey` — `PRIMARY KEY (note_id)`
            |- `note_posters_note_id_fkey` — `FOREIGN KEY (note_id) REFERENCES note.notes(id) ON DELETE CASCADE`
            |
            |## RAG
            |
            |Chunks.
            |
            |### `rag_chunks`
            |
            |Embedded note chunks.
            |
            || Column | Type | Null | Default | Key | Comment |
            ||---|---|---|---|---|---|
            || `id` | `bigint` | no | `generated always as identity` | PK | Row id |
            || `content` | `text` | no | `''::text` |  |  |
            |
            |Constraints:
            |
            |- `rag_chunks_pkey` — `PRIMARY KEY (id)`
            |
            |Indexes:
            |
            |- `idx_rag_chunks_content` — `btree (content)`
            |- `uq_rag_chunks_content` — unique `btree (lower(content))`
            |
            """.trimMargin(),
            text,
        )
    }

    @Test
    fun `a pipe or a line break in a cell cannot break the Markdown table`() {
        val concat = chunks.copy(
            columns = listOf(
                TableColumn("label", "text", nullable = true, default = "('a'::text || 'b'::text)", comment = "two\n lines"),
            ),
            constraints = listOf(TableConstraint("chk", 'c', "CHECK (label <>\n    ''::text)", listOf("label"))),
        )

        val text = SchemaSnapshotRenderer.render(
            emptyList(), sections, mapOf("note_posters" to posters, "rag_chunks" to concat),
        )

        assertTrue("| `label` | `text` | yes | `('a'::text \\|\\| 'b'::text)` |  | two lines |" in text, text)
        assertTrue("- `chk` — `CHECK (label <> ''::text)`" in text, text)
    }

    @Test
    fun `a mapped table without catalog data is an error, not an empty block`() {
        val error = assertThrows<IllegalArgumentException> {
            SchemaSnapshotRenderer.render(emptyList(), sections, mapOf("note_posters" to posters))
        }

        assertEquals("No catalog data for table rag_chunks", error.message)
    }
}
