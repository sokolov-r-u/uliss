package io.uliss.note_service.schema

/** Builds the Markdown text of `SCHEMA.md`: per table, a column table, then its constraints and indexes. */
object SchemaSnapshotRenderer {
    const val UPDATE_COMMAND = "./gradlew :note:updateSchemaSnapshot"

    fun render(
        extensions: List<SchemaExtension>,
        sections: List<SchemaSection>,
        tables: Map<String, TableSchema>,
    ): String = buildString {
        appendLine("# Note service database schema")
        appendLine()
        appendLine("The `note` schema after every Flyway migration, grouped by area. Generated by")
        appendLine("`NoteSchemaSnapshotIntegrationTest` from the Postgres catalog; do not edit by hand.")
        appendLine("Update after a new migration: `$UPDATE_COMMAND`.")
        appendLine()
        appendLine("## Contents")
        appendLine()
        appendLine("- [Extensions](#extensions)")
        sections.forEach { section ->
            appendLine("- [${section.title}](#${anchor(section.title)}) — ${section.tables.joinToString { "`$it`" }}")
        }
        appendLine()
        appendLine("## Extensions")
        appendLine()
        extensions.forEach { appendLine("- `${it.name}` ${it.version} in schema `${it.schema}`") }
        sections.forEach { section ->
            appendLine()
            appendLine("## ${section.title}")
            appendLine()
            appendLine(section.description)
            section.tables.forEach { name ->
                appendTable(requireNotNull(tables[name]) { "No catalog data for table $name" })
            }
        }
    }

    private fun StringBuilder.appendTable(table: TableSchema) {
        appendLine()
        appendLine("### `${table.name}`")
        table.comment?.let {
            appendLine()
            appendLine(it)
        }
        appendLine()
        val withComments = table.columns.any { it.comment != null }
        val headers = listOf("Column", "Type", "Null", "Default", "Key") +
            if (withComments) listOf("Comment") else emptyList()
        appendLine(headers.joinToString(" | ", "| ", " |"))
        appendLine(headers.joinToString("|", "|", "|") { "---" })
        table.columns.forEach { column ->
            val cells = listOf(
                code(column.name),
                code(column.type),
                if (column.nullable) "yes" else "no",
                column.default?.let(::code).orEmpty(),
                keys(table, column.name),
            ) + if (withComments) listOf(cell(column.comment.orEmpty())) else emptyList()
            appendLine(cells.joinToString(" | ", "| ", " |"))
        }
        if (table.constraints.isNotEmpty()) {
            appendLine()
            appendLine("Constraints:")
            appendLine()
            table.constraints.forEach { appendLine("- `${it.name}` — `${oneLine(it.definition)}`") }
        }
        if (table.indexes.isNotEmpty()) {
            appendLine()
            appendLine("Indexes:")
            appendLine()
            table.indexes.forEach {
                appendLine("- `${it.name}` — ${if (it.unique) "unique " else ""}`${oneLine(it.definition)}`")
            }
        }
    }

    /** PK and FK marks of a column; the full definitions are in the constraint list. */
    private fun keys(table: TableSchema, column: String): String {
        val primary = table.constraints.any { it.type == 'p' && column in it.columns }
        // a composite key pairs columns by position, so each column shows the column it really references
        val targets = table.constraints.filter { it.type == 'f' && column in it.columns }
            .map { fk ->
                val target = fk.referencedColumns.getOrNull(fk.columns.indexOf(column))
                listOfNotNull(fk.references, target).joinToString(".")
            }
            .distinct().sorted()
        return (listOfNotNull("PK".takeIf { primary }) + targets.map { "FK → $it" }).joinToString(", ")
    }

    private fun code(text: String): String = "`${cell(text)}`"

    /** A pipe would end the Markdown cell, a line break the row. */
    private fun cell(text: String): String = oneLine(text).replace("|", "\\|")

    /** Pretty-printed catalog definitions may wrap; inline code must stay on one line. */
    private fun oneLine(text: String): String = text.replace(Regex("\\s*\\R\\s*"), " ")

    /** GitHub's heading anchor: lower case, spaces to hyphens, punctuation dropped. */
    private fun anchor(title: String): String =
        title.lowercase().replace(' ', '-').filter { it.isLetterOrDigit() || it == '-' || it == '_' }
}
