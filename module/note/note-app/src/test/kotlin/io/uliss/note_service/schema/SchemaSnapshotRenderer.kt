package io.uliss.note_service.schema

/** Builds the Markdown text of `SCHEMA.md` from normalized per-table DDL. */
object SchemaSnapshotRenderer {
    const val UPDATE_COMMAND = "./gradlew :note:updateSchemaSnapshot"
    private const val FENCE = "```"

    fun render(
        extensions: List<SchemaExtension>,
        sections: List<SchemaSection>,
        tableDdl: Map<String, String>,
    ): String = buildString {
        appendLine("# Note service database schema")
        appendLine()
        appendLine("The `note` schema after every Flyway migration, grouped by area. Generated by")
        appendLine("`NoteSchemaSnapshotIntegrationTest` from `pg_dump`; do not edit by hand.")
        appendLine("Update after a new migration: `$UPDATE_COMMAND`.")
        appendLine()
        appendLine("## Contents")
        appendLine()
        appendLine("- [Extensions](#extensions)")
        sections.forEach { section ->
            appendLine("- [${section.title}](#${anchor(section.title)}) — ${section.tables.joinToString { "`$it`" }}")
        }
        appendLine()
        appendLine("## Extensions")
        appendLine()
        appendLine("${FENCE}sql")
        extensions.forEach { appendLine("CREATE EXTENSION ${it.name} WITH SCHEMA ${it.schema}; -- version ${it.version}") }
        appendLine(FENCE)
        sections.forEach { section ->
            appendLine()
            appendLine("## ${section.title}")
            appendLine()
            appendLine(section.description)
            section.tables.forEach { table ->
                val ddl = requireNotNull(tableDdl[table]) { "No DDL for table $table" }
                appendLine()
                appendLine("### `$table`")
                appendLine()
                appendLine("${FENCE}sql")
                appendLine(ddl)
                appendLine(FENCE)
            }
        }
    }

    /** GitHub's heading anchor: lower case, spaces to hyphens, punctuation dropped. */
    private fun anchor(title: String): String =
        title.lowercase().replace(' ', '-').filter { it.isLetterOrDigit() || it == '-' || it == '_' }
}
